"""Encode the supplied logo as RGB565 for the round display; requires Pillow 11.3.0."""
from pathlib import Path
from PIL import Image, ImageOps

root = Path(__file__).resolve().parents[1]
source = root / 'firmware/assets/cyber-turtle-logo.jpg'
original = ImageOps.exif_transpose(Image.open(source)).convert('RGB')
# Preserve the complete supplied canvas and aspect ratio. No redraw or wrapping.
width = 232
height = round(original.height * width / original.width)
logo = original.resize((width, height), Image.Resampling.LANCZOS)
values = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in logo.getdata()]
rows = [', '.join(f'0x{v:04x}' for v in values[i:i+16]) for i in range(0, len(values), 16)]
header = ('// Generated by scripts/refresh-firmware-logo.py; do not hand edit.\n'
          '#pragma once\n#include <Arduino.h>\n'
          f'constexpr int LOGO_WIDTH = {width}, LOGO_HEIGHT = {height};\n'
          'const uint16_t LOGO_PIXELS[] PROGMEM = {\n  ' + ',\n  '.join(rows) + '\n};\n')
(root / 'firmware/cyber_turtle/Logo.h').write_text(header)
preview = Image.new('RGB', (240, 240), 'black')
preview.paste(logo, ((240-width)//2, (240-height)//2))
output = root / '.local/esp32/build/logo-preview.png'
output.parent.mkdir(parents=True, exist_ok=True)
preview.save(output)
print(f'Encoded {width}x{height}, {len(values)*2} bytes; preview: {output}')
